export function isChaosFaultActive(
  chaos: DataQualityChaosState,
  faultId: QualityChaosId,
): boolean {
  if (faultId === 'null_store_id') return chaos.nullStoreIdPct > 0;
  if (faultId === 'duplicate_vouchers') return chaos.duplicateVoucherCount > 0;
  return chaos.kafkaCdcLagMinutes > 0;
}

export function getActiveChaosIds(chaos: DataQualityChaosState): QualityChaosId[] {
  const active: QualityChaosId[] = [];
  if (chaos.nullStoreIdPct > 0) active.push('null_store_id');
  if (chaos.duplicateVoucherCount > 0) active.push('duplicate_vouchers');
  if (chaos.kafkaCdcLagMinutes > 0) active.push('kafka_cdc_lag');
  return active;
}

export function toggleChaosFault(
  current: DataQualityChaosState,
  faultId: QualityChaosId,
): DataQualityChaosState {
  if (faultId === 'null_store_id') {
    return {
      ...current,
      nullStoreIdPct: current.nullStoreIdPct > 0 ? 0 : 1.8,
    };
  }
  if (faultId === 'duplicate_vouchers') {
    return {
      ...current,
      duplicateVoucherCount: current.duplicateVoucherCount > 0 ? 0 : 412,
    };
  }
  return {
    ...current,
    kafkaCdcLagMinutes: current.kafkaCdcLagMinutes > 0 ? 0 : 45,
  };
}

export function applyChaosFault(
  current: DataQualityChaosState,
  faultId: QualityChaosId,
): DataQualityChaosState {
  if (faultId === 'null_store_id') {
    return { ...current, nullStoreIdPct: 1.8 };
  }
  if (faultId === 'duplicate_vouchers') {
    return { ...current, duplicateVoucherCount: 412 };
  }
  return { ...current, kafkaCdcLagMinutes: 45 };
}

function penaltyForStatus(status: DataQualityStatus, weight: number): number {
  if (status === 'CRITICAL_FAIL') return Number(weight.toFixed(2));
  if (status === 'WARN') return Number((weight * 0.45).toFixed(2));
  return 0;
}

export function formatAssertionStatusBadge(status: DataQualityStatus): string {
  if (status === 'CRITICAL_FAIL') return 'CRITICAL FAIL';
  return status;
}

